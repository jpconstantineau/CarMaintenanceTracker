import { test, expect } from '@playwright/test';

async function openCar(page) {
  await page.goto('./');
  await page.getByRole('button', { name: 'Add vehicle', exact: true }).click();
  await page.getByLabel('Vehicle name (required)').fill('Oil car');
  await page.getByLabel('Kilometres (km)', { exact: true }).check();
  await page.getByRole('button', { name: 'Create vehicle', exact: true }).click();
}

test('record, review, correct and export oil facts and their supported forecast @live', async ({ page }, testInfo) => {
  await openCar(page);
  await page.getByRole('button', { name: 'Record history', exact: true }).click();
  const rows = page.locator('.record-editor');
  for (const [index, date, odometer, life] of [[0, '2025-01-01', '100000', '80'], [1, '2025-02-10', '104000', '40']]) {
    await page.getByText('Oil checks and top-ups', { exact: true }).click();
    await page.getByRole('button', { name: 'Read oil life', exact: true }).click();
    const row = rows.nth(index);
    await expect(row.getByLabel('Date (required)', { exact: true })).toHaveValue('');
    await expect(row.getByLabel('Date (required)', { exact: true })).toHaveAttribute('type', 'date');
    await expect(row.getByLabel('Odometer (optional)')).toHaveValue('');
    await expect(row.getByLabel('Odometer (optional)')).toHaveAttribute('type', 'number');
    await row.getByLabel('Date (required)', { exact: true }).fill(date);
    await row.getByLabel('Odometer (optional)').fill(odometer);
    await row.getByLabel('Oil life (%, optional)').fill(life);
  }
  await page.getByRole('button', { name: 'Save records', exact: true }).click();
  await page.getByRole('button', { name: 'Vehicle summary', exact: true }).click();
  await expect(page.locator('#oil-status')).toContainText('108,000 km');
  await page.getByRole('button', { name: 'Oil history and forecast', exact: true }).click();
  await expect(page.locator('#oil-title')).toBeFocused();
  await expect(page.locator('#oil-details')).toContainText('4,000 km remaining');
  await expect(page.locator('#oil-details')).toContainText('Limited evidence: 2 readings');
  await expect(page.locator('#oil-details')).toContainText('2025-03-22');
  await expect(page.locator('#oil-details')).toContainText('80%');
  await expect(page.locator('#oil-details')).toContainText('Earlier oil change unknown');
  await page.screenshot({ path: testInfo.outputPath('oil-forecast-light.png'), fullPage: true });
  await page.getByRole('button', { name: 'Check oil level', exact: true }).click();
  await expect(rows.getByLabel('Date (required)', { exact: true })).toHaveValue('');
  await expect(rows.getByLabel('Odometer (optional)')).toHaveValue('');
  await rows.getByLabel('Date (required)', { exact: true }).fill('2025-02-11');
  await rows.getByLabel('Oil level', { exact: true }).selectOption('low');
  await rows.getByLabel('Notes (optional)').fill('<b>Below mark</b>');
  await page.getByRole('button', { name: 'Save records', exact: true }).click();
  await page.getByRole('button', { name: 'Vehicle summary', exact: true }).click();
  await page.getByRole('button', { name: 'Oil history and forecast', exact: true }).click();
  await page.getByRole('button', { name: 'Top up oil', exact: true }).click();
  await expect(rows.getByLabel('Date (required)', { exact: true })).toHaveValue('');
  await expect(rows.getByLabel('Odometer (optional)')).toHaveValue('');
  await rows.getByLabel('Date (required)', { exact: true }).fill('2025-02-12');
  await rows.getByLabel('Oil added (litres, optional)').fill('0');
  await page.getByRole('button', { name: 'Save records', exact: true }).click();
  await expect(rows.getByLabel('Oil added (litres, optional)')).toBeFocused();
  await expect(rows.getByLabel('Oil added (litres, optional)')).toHaveAttribute('aria-invalid', 'true');
  await rows.getByLabel('Oil added (litres, optional)').fill('0.625');
  await page.getByRole('button', { name: 'Save records', exact: true }).click();
  await expect(page.locator('#history-list')).toContainText('0.625 L');
  await expect(page.locator('#history-list')).toContainText('Oil level: low');
  await expect(page.locator('#history-list b')).toHaveCount(0);
  await page.getByRole('button', { name: 'Edit record 3', exact: true }).click();
  await rows.getByLabel('Oil life (%, optional)').fill('0');
  await page.getByRole('button', { name: 'Save record', exact: true }).click();
  await page.getByRole('button', { name: 'Vehicle summary', exact: true }).click();
  await expect(page.locator('#oil-status')).toContainText('Due — recorded oil life is 0%');
  await page.reload();
  await expect(page.locator('#oil-status')).toContainText('Due — recorded oil life is 0%');
  await page.getByRole('button', { name: 'JSON backups', exact: true }).click();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export JSON', exact: true }).click();
  await page.getByLabel('App JSON file').setInputFiles(await (await download).path());
  await page.getByRole('button', { name: 'Preview import', exact: true }).click();
  await expect(page.locator('#import-counts')).toContainText('0 additions, 0 conflicts');
});

test('oil changes retain item details and incomplete checks at narrow enlarged layouts @live', async ({ page }, testInfo) => {
  await openCar(page);
  await page.getByRole('button', { name: 'Add maintenance item', exact: true }).click();
  await page.getByLabel('Item name (required)').fill('Engine oil');
  await page.getByRole('button', { name: 'Save item', exact: true }).click();
  await page.getByRole('button', { name: 'Vehicle summary', exact: true }).click();
  await page.getByRole('button', { name: 'Oil history and forecast', exact: true }).click();
  await page.getByRole('button', { name: 'Change oil', exact: true }).focus();
  await page.keyboard.press('Enter');
  const row = page.locator('.record-editor');
  await expect(row.getByLabel('Date (required)', { exact: true })).toBeFocused();
  await expect(row.getByLabel('Date (required)', { exact: true })).toHaveValue('');
  await expect(row.getByLabel('Odometer (optional)')).toHaveValue('');
  await row.getByLabel('Maintenance item (optional)').selectOption({ label: 'Engine oil' });
  await row.getByLabel('Date precision', { exact: true }).selectOption('month');
  await row.getByLabel('Date (required)', { exact: true }).fill('2025-01');
  await row.getByLabel('Part used (optional)').fill('0W-20');
  await page.getByRole('button', { name: 'Save records', exact: true }).click();
  await expect(page.locator('#history-list > li')).toHaveCount(1);
  await page.getByRole('button', { name: 'Edit record 1', exact: true }).click();
  await expect(row.getByLabel('Maintenance item (optional)')).toHaveValue(/.+/);
  await expect(row.getByLabel('Part used (optional)')).toHaveValue('0W-20');
  await page.getByRole('button', { name: 'Save record', exact: true }).click();
  await expect(page.locator('#history-list > li')).toHaveCount(1);
  await page.getByRole('button', { name: 'Vehicle summary', exact: true }).click();
  await page.getByRole('button', { name: 'Oil history and forecast', exact: true }).click();
  await page.getByRole('button', { name: 'Read oil life', exact: true }).click();
  await row.getByLabel('Date (required)', { exact: true }).fill('2025-02-01');
  await row.getByLabel('Oil life (%, optional)').fill('101');
  await page.getByRole('button', { name: 'Save records', exact: true }).click();
  await expect(row.getByLabel('Oil life (%, optional)')).toBeFocused();
  await expect(row.getByLabel('Oil life (%, optional)')).toHaveAttribute('aria-invalid', 'true');
  await row.getByLabel('Oil life (%, optional)').fill('');
  await page.getByRole('button', { name: 'Save records', exact: true }).click();
  await expect(page.locator('#history-list')).toContainText('Oil life unknown');
  await page.getByRole('button', { name: 'Vehicle summary', exact: true }).click();
  await page.getByRole('button', { name: 'Oil history and forecast', exact: true }).click();
  await page.getByLabel('Theme', { exact: true }).selectOption('dark');
  await page.setViewportSize({ width: 320, height: 900 });
  await page.evaluate(() => { document.documentElement.style.fontSize = '200%'; });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'View oil records', exact: true }).focus();
  await page.screenshot({ path: testInfo.outputPath('oil-dark-narrow.png'), fullPage: true });
  await page.keyboard.press('Enter');
  await expect(page.locator('#history-list > li')).toHaveCount(2);
});
